# ========= 配置 =========
AMAP_KEY = "731df7f33e6cff66bcf24378ce6a2b05"
html_name = "amap_route.html"

# 拼接高德坐标字符串 "lng,lat;lng,lat;..."
path_str = ";".join([f"{lng},{lat}" for lng, lat in points])
center_lng, center_lat = points[0]

# ========= HTML 模板 =========
html_template = f'''<!DOCTYPE html>
<html lang="zh-CN">
<head>
    <meta charset="utf-8">
    <title>高德地图路径可视化</title>
    <style>
        body {{ margin: 0; }}
        #container {{ width: 100%; height: 100vh; }}
    </style>
</head>
<body>
    <div id="container"></div>
    <script src="https://webapi.amap.com/maps?v=2.0&key={AMAP_KEY}"></script>
    <script>
        var map = new AMap.Map("container", {{
            zoom: 16,
            center: [{center_lng}, {center_lat}],
            resizeEnable: true
        }});

        // 解析路径
        var path = "{path_str}".split(";").map(function(item){{
            var arr = item.split(",");
            return new AMap.LngLat(parseFloat(arr[0]), parseFloat(arr[1]));
        }});

        // 绘制轨迹线
        var polyline = new AMap.Polyline({{
            path: path,
            strokeColor: "#2E86AB",
            strokeWeight: 5,
            strokeOpacity: 0.85,
            lineJoin: "round"
        }});
        map.add(polyline);

        // 起点标记
        var startMarker = new AMap.Marker({{
            position: path[0],
            icon: new AMap.Icon({{
                size: new AMap.Size(25, 34),
                image: "https://webapi.amap.com/theme/v1.3/markers/n/start.png"
            }})
        }});
        map.add(startMarker);

        // 终点标记
        var endMarker = new AMap.Marker({{
            position: path[path.length - 1],
            icon: new AMap.Icon({{
                size: new AMap.Size(25, 34),
                image: "https://webapi.amap.com/theme/v1.3/markers/n/end.png"
            }})
        }});
        map.add(endMarker);

        // 自动适配视野
        map.setFitView();
    </script>
</body>
</html>'''

# ========= 写入文件 =========
with open(html_name, "w", encoding="utf-8") as f:
    f.write(html_template)

print(f" 地图文件已生成：{html_name}")
